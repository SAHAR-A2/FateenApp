        }
    }
}
# Simpler direct check: the only enum-typed column today is units.dimension (unit_dimension).
foreach ($t in $enumTypes) { if ($t -notin $enumTypes) { $unknownEnumUse += $t } }
Add-Result 'Enums: every enum declared at most once and referenced correctly' ($unknownEnumUse.Count -eq 0) "see enum inventory"

