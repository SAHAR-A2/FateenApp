# Every lookup/core-entity table that declares a status_id column must FK it to
# lifecycle_statuses(id); translation tables are governed by translation_status.
# Parsed per FOREIGN KEY statement (never across statements) so a table whose own
# status FK is lazily skipped by a cross-statement regex cannot be misattributed.
$statusFkTables = @()
foreach ($f in (Get-Files 'schema\03-constraints')) {
    $txt = [System.IO.File]::ReadAllText($f.FullName)
    foreach ($m in [regex]::Matches($txt, 'ALTER\s+TABLE\s+(\w+)\s+ADD\s+CONSTRAINT\s+\w+\s+FOREIGN\s+KEY\s*\(\s*(\w+)\s*\)\s*REFERENCES\s+(\w+)\s*\(\s*(\w+)\s*\)')) {
        if ($m.Groups[2].Value -eq 'status_id' -and $m.Groups[3].Value -eq 'lifecycle_statuses' -and $m.Groups[4].Value -eq 'id') {
            $statusFkTables += $m.Groups[1].Value
        }
    }
}
$tablesWithStatus = @()
foreach ($f in (Get-Files 'schema\02-tables')) {
    $txt = [System.IO.File]::ReadAllText($f.FullName)
    if ($txt -match '\bstatus_id\b') { $tablesWithStatus += ($f.BaseName -replace '^\d+_', '') }
}
$expectStatusFk = @($tablesWithStatus | Where-Object { $_ -ne 'lifecycle_statuses' -and $_ -notmatch '_translations$' -and $_ -notin $searchTables })
$missingStatusFk = @($expectStatusFk | Where-Object { $_ -notin $statusFkTables })
Add-Result 'Constraints: every table with status_id FKs it -> lifecycle_statuses(id)' ($missingStatusFk.Count -eq 0) ("missing: " + ($missingStatusFk -join ', '))

