# =============================================================================
# validate_foundation.ps1 - static engineering review of the Foundation Layer
# -----------------------------------------------------------------------------
# Purpose:       Enforce the mission self-review checklist: no duplicate enums or
#                tables, no missing constraints/indexes, FK integrity, migration
#                order, naming consistency, documentation coverage, and schema/
#                migration sync. Designed to be run in CI after any change.
#
# Usage:         powershell -ExecutionPolicy Bypass -File scripts/validate_foundation.ps1
#
# Exit code:     0 = all checks passed; 1 = one or more failures.
# Note:          ASCII-only file (PowerShell 5.1 ANSI parsing).
# =============================================================================

$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot | Split-Path -Parent
$results = New-Object System.Collections.Generic.List[object]

function Add-Result([string]$name, [bool]$ok, [string]$detail) {
    $results.Add([pscustomobject]@{ Check = $name; Status = $(if ($ok) { 'PASS' } else { 'FAIL' }); Detail = $detail })
}

function Get-Files([string]$relDir, [string]$filter = '*.sql') {
    $dir = Join-Path $root $relDir
    if (-not (Test-Path -LiteralPath $dir)) { return @() }
    return Get-ChildItem -LiteralPath $dir -Filter $filter | Sort-Object Name
}

$migrationDir = Join-Path $root 'migrations'

# --- 1. Migration inventory --------------------------------------------------
$migs = Get-Files 'migrations' '*.sql'
$migNames = @($migs | ForEach-Object { $_.Name })
$migPrefixes = @($migs | ForEach-Object {
    if ($_.Name -match '^(\d{4})_.+\.sql$') { $matches[1] } else { 'BAD' }
})
$badNames = @($migNames | Where-Object { $_ -notmatch '^\d{4}_[a-z0-9_]+\.sql$' })
Add-Result 'Migrations: naming convention NNNN_name.sql' ($badNames.Count -eq 0) ("files: " + $migNames -join ', ')

$expectedPrefixes = @('0001','0002','0003','0004','0005','0006','0007','0008','0009','0010','0011','0012','0013','0014','0015','0016','0017','0018','0019','0020','0021','0022','0023','0024','0025','0026','0027','0028','0029','0030','0031','0032','0033','0034','0035','0036','0037','0038','0039')
$prefixMatch = ($migPrefixes.Count -eq $expectedPrefixes.Count) -and
(([string]::Join(',', $migPrefixes)) -eq ([string]::Join(',', $expectedPrefixes)))
Add-Result 'Migrations: contiguous 0001-0039, no gaps/duplicates' $prefixMatch ("found: " + ($migPrefixes -join ', '))

# --- 2. Schema/migration sync (regenerate and compare) -----------------------
$snapshot = @{}
foreach ($m in $migs) { $snapshot[$m.Name] = (Get-FileHash -LiteralPath $m.FullName -Algorithm MD5).Hash }
& powershell -NoProfile -ExecutionPolicy Bypass -File (Join-Path $root 'scripts\build_migrations.ps1') | Out-Null
$synced = $true
$syncDetail = ''
foreach ($m in (Get-Files 'migrations' '*.sql')) {
    $h = (Get-FileHash -LiteralPath $m.FullName -Algorithm MD5).Hash
    if (-not $snapshot.ContainsKey($m.Name)) { $synced = $false; $syncDetail = "unexpected file $($m.Name)" }
    elseif ($snapshot[$m.Name] -ne $h) { $synced = $false; $syncDetail = "drift in $($m.Name)" }
}
Add-Result 'Schema/migration sync (regenerated byte-identical)' $synced $syncDetail

# --- 3. Enum uniqueness ------------------------------------------------------
$enumTypes = @()
foreach ($f in (Get-Files 'schema\01-enums')) {
    $txt = [System.IO.File]::ReadAllText($f.FullName)
    if ($txt -match 'CREATE\s+TYPE\s+(\w+)\s+AS\s+ENUM') { $enumTypes += $matches[1] }
}
$dupEnums = @($enumTypes | Group-Object | Where-Object { $_.Count -gt 1 } | Select-Object -ExpandProperty Name)
Add-Result 'Enums: unique, no duplicates' ($dupEnums.Count -eq 0) ("count=$($enumTypes.Count); " + ($enumTypes -join ', '))

# Enum filename must match the type it declares.
$enumNameMismatch = @()
foreach ($f in (Get-Files 'schema\01-enums')) {
    $expected = ($f.BaseName -replace '^\d+_', '')
    if ($expected -notin $enumTypes) { $enumNameMismatch += $f.Name }
}
Add-Result 'Enums: filename matches declared type' ($enumNameMismatch.Count -eq 0) ("mismatched: " + ($enumNameMismatch -join ', '))

# --- 4. Table uniqueness -----------------------------------------------------
$tables = @()
foreach ($f in (Get-Files 'schema\02-tables')) {
    $txt = [System.IO.File]::ReadAllText($f.FullName)
    if ($txt -match 'CREATE\s+TABLE\s+(\w+)') { $tables += $matches[1] }
}
$dupTables = @($tables | Group-Object | Where-Object { $_.Count -gt 1 } | Select-Object -ExpandProperty Name)
Add-Result 'Tables: unique, no duplicates' ($dupTables.Count -eq 0) ("count=$($tables.Count); " + ($tables -join ', '))

# Mission 04 relationship/junction tables: keyed by endpoint FKs + relationship
# columns, not by a natural code, so the (code | internal_code) rule does not apply.
$relationshipTables = @('product_ingredients','product_allergens','product_nutrition_values','product_health_flags','ingredient_allergens','ingredient_health_flags','ingredient_aliases','entity_relationships','product_images','product_barcodes')

# Mission 05 history tables: immutable INSERT-only snapshots. They intentionally
# carry no updated_at/deleted_at (immutable), no code/internal_code UNIQUE (several
# versions share one entity code), and are exempt from the plural-name heuristic.
# Mission 05 audit tables: operational infrastructure, not governed entities, so
# they carry no status_id and (except entity_versions) no version_number.
# Mission 07 history tables (images_history, barcodes_history) follow the same
# Mission 05 history architecture and join the same exemption list.
$historyTables = @('companies_history','brands_history','products_history','ingredients_history','allergens_history','health_flags_history','nutrition_types_history','product_categories_history','ingredient_categories_history','images_history','barcodes_history','product_images_history','product_barcodes_history')
$auditTables = @('audit_context','change_sets','audit_events','audit_log','entity_versions','version_metadata')
$infrastructureTables = $historyTables + $auditTables

# Mission 08 search tables: DERIVED READ MODELS, not governed entities. They
# deliberately carry NO status_id, NO version_number, NO audit trio, and NO
# natural code; they carry a logical {entity}_id with UNIQUE but no FK. They are
# exempt from the governed-entity heuristics and validated by their own block.
$searchTables = @('product_search_index','ingredient_search_index','brand_search_index','company_search_index')

$tableNameMismatch = @()
foreach ($f in (Get-Files 'schema\02-tables')) {
    $expected = ($f.BaseName -replace '^\d+_', '')
    if ($expected -notin $tables) { $tableNameMismatch += $f.Name }
}
Add-Result 'Tables: filename matches table name' ($tableNameMismatch.Count -eq 0) ("mismatched: " + ($tableNameMismatch -join ', '))

# Plural table names (heuristic). Infrastructure/history names are conventional
# singulars/mass nouns (audit_context, audit_log, version_metadata, *_history);
# Mission 08 search tables use the singular *_search_index form (mission-named).
$nonPlural = @($tables | Where-Object { $_ -notmatch 's$' -and $_ -notin $infrastructureTables -and $_ -notin $searchTables })
Add-Result 'Tables: plural names' ($nonPlural.Count -eq 0) ("non-plural: " + ($nonPlural -join ', '))

# --- 5. Per-table structural invariants -------------------------------------
$missingPk = @(); $missingUuid = @(); $missingAudit = @(); $missingStatus = @()
$missingCodeUnique = @(); $missingComment = @()
$missingVersion = @(); $missingVersionCheck = @()
$enumCols = @{}
foreach ($t in $enumTypes) { $enumCols[$t] = $true }

foreach ($f in (Get-Files 'schema\02-tables')) {
    $txt = [System.IO.File]::ReadAllText($f.FullName)
    $tbl = ($f.BaseName -replace '^\d+_', '')
    if ($txt -notmatch 'PRIMARY\s+KEY') { $missingPk += $tbl }
    if ($txt -notmatch 'gen_random_uuid\(\)' -and $tbl -ne 'lifecycle_statuses') { $missingUuid += $tbl }
    # History tables are immutable INSERT-only: they intentionally have no
    # updated_at/deleted_at, so only created_at is required there. Search tables
    # are derived read models with no audit trio at all (validated separately).
    if ($tbl -notin $historyTables -and $tbl -notin $searchTables -and ($txt -notmatch 'created_at' -or $txt -notmatch 'updated_at' -or $txt -notmatch 'deleted_at')) { $missingAudit += $tbl }
    # Translation tables carry translation_status (ENUM), not status_id; audit
    # infrastructure tables carry no status_id at all; search tables carry no
    # lifecycle state (derived read models).
    if ($txt -notmatch 'status_id' -and $tbl -ne 'lifecycle_statuses' -and $tbl -notmatch '_translations$' -and $tbl -notin $auditTables -and $tbl -notin $searchTables) { $missingStatus += $tbl }
    # Lookup tables use code; canonical core entities use internal_code.
    # Mission 07 canonical entities use their natural key: barcodes.barcode,
    # images.content_hash. Translation tables are keyed by (entity_id,
    # language_id) and have neither; relationship/junction tables are keyed by
    # endpoint FKs and the relationship column set; history/audit tables are
    # keyed by version identity. Search tables are keyed by UNIQUE ({entity}_id)
    # (checked in the Mission 08 block).
    if ($txt -notmatch 'UNIQUE\s*\(\s*(code|internal_code|barcode|content_hash)\s*\)' -and $tbl -notmatch '_translations$' -and $tbl -notin $relationshipTables -and $tbl -notin $infrastructureTables -and $tbl -notin $searchTables) { $missingCodeUnique += $tbl }
    # History tables and entity_versions carry version_number; the remaining
    # audit tables are operational logs without a version counter; search tables
    # are derived read models with no governance counter.
    if (($tbl -notin $auditTables -or $tbl -eq 'entity_versions') -and $tbl -notin $searchTables -and $txt -notmatch 'version_number') { $missingVersion += $tbl }
    if (($tbl -notin $auditTables -or $tbl -eq 'entity_versions') -and $tbl -notin $searchTables -and $txt -notmatch 'CHECK\s*\(\s*version_number\s*>\s*0\s*\)') { $missingVersionCheck += $tbl }
    if (-not $txt.TrimStart().StartsWith('--')) { $missingComment += $tbl }
}
Add-Result 'Tables: id uuid PRIMARY KEY gen_random_uuid() (lifecycle_statuses = BIGINT identity exception)' ($missingPk.Count -eq 0 -and $missingUuid.Count -eq 0) ("missing: " + ($missingPk + $missingUuid) -join ', ')
Add-Result 'Tables: created_at/updated_at/deleted_at present' ($missingAudit.Count -eq 0) ("missing: " + ($missingAudit -join ', '))
Add-Result 'Tables: status_id lifecycle column present (ADR-008; translations use translation_status)' ($missingStatus.Count -eq 0) ("missing: " + ($missingStatus -join ', '))
Add-Result 'Tables: version_number governance column present' ($missingVersion.Count -eq 0) ("missing: " + ($missingVersion -join ', '))
Add-Result 'Tables: version_number CHECK (> 0) present' ($missingVersionCheck.Count -eq 0) ("missing: " + ($missingVersionCheck -join ', '))
Add-Result 'Tables: natural UNIQUE key present (code | internal_code | barcode | content_hash)' ($missingCodeUnique.Count -eq 0) ("missing: " + ($missingCodeUnique -join ', '))
Add-Result 'Tables: documentation header on every file' ($missingComment.Count -eq 0) ("missing: " + ($missingComment -join ', '))

# Translation tables must carry entity_id + language_id + translation_status and
# a uniqueness constraint over (entity_id, language_id).
$missingTransStruct = @()
foreach ($f in (Get-Files 'schema\02-tables')) {
