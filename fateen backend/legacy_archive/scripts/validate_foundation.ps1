            $missingTransStruct += $tbl
        }
    }
}
Add-Result 'Translations: entity_id + language_id + translation_status + UNIQUE(entity, language)' ($missingTransStruct.Count -eq 0) ("missing: " + ($missingTransStruct -join ', '))

