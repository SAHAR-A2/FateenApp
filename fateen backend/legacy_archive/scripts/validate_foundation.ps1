# --- 5c. Mission 08 search-layer invariants -----------------------------------
# Search tables are DERIVED READ MODELS: logical {entity}_id with UNIQUE but no
# FK, normalized searchable text/tokens, a ranking helper, and generated_at.
# They must NOT carry governance/lifecycle/audit columns and must NOT be FK
# targets, so the layer is completely disposable and rebuildable.
$missingSearch = @($searchTables | Where-Object { $_ -notin $tables })
Add-Result 'Search: all 4 search index tables present' ($missingSearch.Count -eq 0) ("missing: " + ($missingSearch -join ', '))

$badSearchStruct = @(); $searchFkRefs = @()
foreach ($f in (Get-Files 'schema\02-tables')) {
    $tbl = ($f.BaseName -replace '^\d+_', '')
    if ($tbl -in $searchTables) {
        $txt = [System.IO.File]::ReadAllText($f.FullName)
        $eid = ($tbl -replace '_search_index$', '_id')
        foreach ($c in @('search_name','search_text','search_tokens','language_codes','search_rank','generated_at')) {
            if ($txt -notmatch ("\b" + [regex]::Escape($c) + "\b")) { $badSearchStruct += "${tbl}:${c}" }
        }
        if ($txt -notmatch ("\b" + [regex]::Escape($eid) + "\s+uuid")) { $badSearchStruct += "${tbl}:${eid} uuid" }
        if ($txt -notmatch ("UNIQUE\s*\(\s*" + [regex]::Escape($eid) + "\s*\)")) { $badSearchStruct += "${tbl}:UNIQUE($eid)" }
        if ($txt -notmatch 'CHECK\s*\(\s*search_rank\s*>=\s*0\s*\)') { $badSearchStruct += "${tbl}:search_rank>=0" }
        # Column declarations only (prose in file headers may mention the
        # concepts; this checks the actual column layout).
        foreach ($no in @('status_id','version_number','created_at','updated_at','deleted_at','is_active')) {
            if ($txt -match ("^\s*" + [regex]::Escape($no) + "\s+(bigint|integer|numeric|text|citext|uuid|timestamptz|boolean|jsonb)")) { $badSearchStruct += "${tbl}:has ${no}" }
        }
        if ($txt -match 'REFERENCES\s+\w+') { $searchFkRefs += $tbl }
    }
}
Add-Result 'Search: derived read-model structure (entity_id UNIQUE, no FK, search fields, no governance)' ($badSearchStruct.Count -eq 0) ("issues: " + ($badSearchStruct -join ', '))
Add-Result 'Search: no inline FOREIGN KEY (REFERENCES) in search tables' ($searchFkRefs.Count -eq 0) ("with FK: " + ($searchFkRefs -join ', '))

# Search tables are not FK targets of any constraints file.
$constraintTxt = ''
foreach ($f in (Get-Files 'schema\03-constraints')) { $constraintTxt += [System.IO.File]::ReadAllText($f.FullName) + "`n" }
$searchFkTargets = @($searchTables | Where-Object { $constraintTxt -match ('REFERENCES\s+' + [regex]::Escape($_)) })
Add-Result 'Search: no foreign keys reference search tables (fully rebuildable)' ($searchFkTargets.Count -eq 0) ("referenced: " + ($searchFkTargets -join ', '))

# Search-only indexes: GIN trigram on search_name/search_text (pg_trgm, ADR-003),
# GIN on search_tokens, btree on search_rank DESC - for every search table.
$searchIndexTxt = ''
